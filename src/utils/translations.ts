export type Language = 'en' | 'ru';

export function formatFileSize(bytes: number, lang: Language = 'en'): string {
  if (bytes < 1024) {
    return lang === 'en' ? `${bytes} bytes` : `${bytes} байт`;
  }
  if (bytes < 1024 * 1024) {
    return lang === 'en' ? `${(bytes / 1024).toFixed(1)} KB` : `${(bytes / 1024).toFixed(1)} КБ`;
  }
  return lang === 'en' ? `${(bytes / (1024 * 1024)).toFixed(2)} MB` : `${(bytes / (1024 * 1024)).toFixed(2)} МБ`;
}

export function formatTenge(amount: number, lang: Language = 'en'): string {
  const locale = lang === 'en' ? 'en-US' : 'ru-RU';
  return new Intl.NumberFormat(locale).format(Math.round(amount)) + ' ₸';
}

export function formatDaysGenitive(days: string, lang: Language = 'en'): string {
  const n = parseInt(days, 10);
  if (isNaN(n)) return lang === 'en' ? `${days} days` : `${days} дней`;
  if (lang === 'en') {
    return n === 1 ? '1 day' : `${n} days`;
  }
  if (n === 1) return '1 дня';
  return `${n} дней`;
}

export function formatDateTime(date: Date | number | string, lang: Language = 'en'): string {
  if (!date) return '';
  let d: Date;
  if (typeof date === 'number') {
    d = new Date(date);
  } else if (date instanceof Date) {
    d = date;
  } else {
    const parsed = Date.parse(date);
    if (!isNaN(parsed)) {
      d = new Date(parsed);
    } else {
      return String(date);
    }
  }

  const locale = lang === 'en' ? 'en-US' : 'ru-RU';
  return (
    new Intl.DateTimeFormat(locale, {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: false,
      timeZone: 'Asia/Almaty',
    }).format(d) + ' GMT+5'
  );
}

export function formatTrapsHeadline(count: number, lang: Language = 'en'): string {
  if (lang === 'en') {
    if (count === 1) return 'Found 1 clause to pay close attention to';
    return `Found ${count} clauses to pay close attention to`;
  }
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod100 >= 11 && mod100 <= 14) {
    return `Найдено ${count} условий, на которые стоит обратить внимание`;
  }
  if (mod10 === 1) {
    return `Найдено ${count} условие, на которое стоит обратить внимание`;
  }
  if (mod10 >= 2 && mod10 <= 4) {
    return `Найдено ${count} условия, на которые стоит обратить внимание`;
  }
  return `Найдено ${count} условий, на которые стоит обратить внимание`;
}

