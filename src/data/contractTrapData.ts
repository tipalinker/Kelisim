export type RiskLevel = 'high' | 'medium';

export interface RiskTrapItem {
  id: string;
  clauseNumber: string;
  title: string;
  riskLevel: RiskLevel;
  quote: string;
  dangerExplanation: string;
  calculationTenge?: {
    amountText: string;
    details: string;
  };
  recommendation: string;
}

export interface ContractFinancialLosses {
  totalEstimated: string;
  note: string;
  breakdown: Array<{
    clause: string;
    title: string;
    amount: string;
  }>;
}

export interface ImportantDateItem {
  id: string;
  title: string;
  deadlineText: string;
}

